import 'dotenv/config';
import {chromium,expect} from '@playwright/test';
import {mkdirSync} from 'node:fs';
import {db} from '../server/db';

const origin=process.env.APP_ORIGIN??'http://127.0.0.1:5173';
if(process.env.NODE_ENV!=='development'||!['localhost','127.0.0.1','[::1]'].includes(new URL(origin).hostname))throw new Error('Use the local development app for this check.');
const user=await db.user.findUniqueOrThrow({where:{email:process.env.SEED_EMAIL??''}});
const area=await db.area.findFirstOrThrow({where:{orgId:user.orgId,name:'Cabinet simulation'}});
await db.$disconnect();
mkdirSync('.local',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1500,height:1100}});
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 const login=await page.request.post(origin+'/api/login',{headers:{Origin:origin},data:{email:process.env.SEED_EMAIL,password:process.env.SEED_PASSWORD}});
 if(!login.ok())throw new Error('Local login failed: HTTP '+login.status());
 await page.goto(origin+'/?department='+area.id);
 const customizer=page.locator('.department-controls>.view-customizer');
 const openMenu=async()=>{if(!await customizer.evaluate(element=>(element as HTMLDetailsElement).open))await customizer.locator('summary').click();};
 const closeMenu=async()=>{await customizer.locator('summary').press('Escape');};
 await expect(page.locator('[data-metric]')).toHaveCount(6);
 await page.getByRole('button',{name:'Hide Completed',exact:true}).click();
 await expect(page.locator('[data-metric="metricCompleted"]')).toHaveCount(0);
 await expect(page.locator('[data-metric]')).toHaveCount(5);
 await page.getByRole('button',{name:'Hide Build stations',exact:true}).click();
 await page.getByRole('button',{name:'Hide Cabinet log',exact:true}).click();
 await page.getByRole('button',{name:'Hide Station speed summary',exact:true}).click();
 await page.locator('.department-detail-sections>summary').click();
 await page.getByRole('button',{name:'Hide Workstation details table',exact:true}).click();
 await page.getByRole('button',{name:'Hide Operator activity',exact:true}).click();
 await expect(page.locator('.build-stations,.cabinet-history,.station-pace-board')).toHaveCount(0);
 await page.reload();
 await expect(page.getByRole('heading',{name:'Cabinet simulation cabinet progress'})).toBeVisible();
 await expect(page.locator('[data-metric]')).toHaveCount(5);
 await expect(page.locator('.build-stations,.cabinet-history,.station-pace-board')).toHaveCount(0);
 await openMenu();
 expect(await customizer.locator('label:has(input[type="checkbox"])').first().evaluate(element=>element.getBoundingClientRect().height)).toBeLessThan(45);
 await expect(customizer.getByRole('checkbox',{name:'Completed',exact:true})).not.toBeChecked();
 await page.screenshot({path:'.local/department-customize-dark.png',fullPage:true});
 await customizer.getByRole('checkbox',{name:'Cabinet log',exact:true}).check();
 await expect(page.locator('.cabinet-history')).toBeVisible();
 await closeMenu();
 await page.getByLabel('Department',{exact:true}).selectOption({label:'Assembly'});
 await openMenu();
 await expect(customizer.getByRole('checkbox',{name:'Completed',exact:true})).toBeChecked();
 await closeMenu();
 await page.getByRole('button',{name:'Show active cabinets'}).click();
 await expect(page.locator('[data-metric="metricCompleted"]')).toHaveCount(0);
 await openMenu();
 await customizer.getByRole('button',{name:'Show all',exact:true}).click();
 await customizer.getByRole('checkbox',{name:'Summary metrics',exact:true}).uncheck();
 await expect(page.locator('.cabinet-metrics')).toHaveCount(0);
 await customizer.getByRole('checkbox',{name:'Summary metrics',exact:true}).check();
 await closeMenu();
 await expect(page.locator('[data-metric]')).toHaveCount(6);
 await page.getByRole('tab',{name:'Graph',exact:true}).click();
 await page.getByRole('button',{name:'Hide Output graph',exact:true}).click();
 await expect(page.getByRole('tab',{name:'Graph',exact:true})).toHaveCount(0);
 await openMenu();
 await customizer.getByRole('checkbox',{name:'Output graph',exact:true}).check();
 await closeMenu();
 await page.getByRole('button',{name:'Hide Cabinet progress',exact:true}).click();
 await expect(page.locator('.cabinet-progress')).toHaveCount(0);
 await openMenu();
 await customizer.getByRole('button',{name:'Show all',exact:true}).click();
 await closeMenu();
 await page.getByTitle('Show cabinet progress full screen',{exact:true}).click();
 await expect(page.locator('.cabinet-progress:fullscreen')).toBeVisible();
 await page.getByRole('button',{name:'Hide Cabinet log',exact:true}).click();
 const fullscreenMenu=page.locator('.cabinet-progress:fullscreen .view-customizer');
 await fullscreenMenu.locator('summary').click();
 await fullscreenMenu.getByRole('checkbox',{name:'Cabinet log',exact:true}).check();
 await expect(page.locator('.cabinet-history')).toBeVisible();
 await fullscreenMenu.locator('summary').press('Escape');
 await page.getByTitle('Exit full screen',{exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await openMenu();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'.local/department-customize-mobile.png'});
 expect(errors).toEqual([]);
 console.log('Department customization passed: hide and restore sections and individual metrics, persistence, independent departments, fullscreen recovery, and mobile layout.');
}finally{await browser.close();}
